const LOCALES = { en: "en-GB", it: "it-IT" };

export function locale(lang) {
  return LOCALES[lang] || LOCALES.en;
}

export function tr(lang, key, vars = {}) {
  const text = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

export function count(lang, value) {
  return Math.round(value).toLocaleString(locale(lang));
}

export function joinNames(lang, names) {
  if (names.length < 2) return names.join("");
  return `${names.slice(0, -1).join(", ")} ${tr(lang, "list.and")} ${names.at(-1)}`;
}

export function hourText(lang, label) {
  const [time, part] = label.split(" · ");
  if (!part) return label;
  return `${time} · ${tr(lang, `hour.${part}`)}`;
}

const DAYS = { Monday: "lunedì", Tuesday: "martedì", Wednesday: "mercoledì", Thursday: "giovedì", Friday: "venerdì", Saturday: "sabato", Sunday: "domenica" };
const MONTHS = { Jan: "gen", Feb: "feb", Mar: "mar", Apr: "apr", May: "mag", Jun: "giu", Jul: "lug", Aug: "ago", Sep: "set", Oct: "ott", Nov: "nov", Dec: "dic" };

function italianDate(text) {
  return text
    .replace(/\b(Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday)\b/g, (day) => DAYS[day])
    .replace(/\b(\d{1,2}) (Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{4})\b/g, (match, d, m, y) => `${d} ${MONTHS[m]} ${y}`);
}

