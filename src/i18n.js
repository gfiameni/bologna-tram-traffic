export function noteText(lang, text) {
  if (!text || lang !== "it") return text;
  if (ITALIAN_NOTES[text]) return ITALIAN_NOTES[text];
  let out = text;
  for (const [pattern, replacement] of ITALIAN_PATTERNS) out = out.replace(pattern, replacement);
  return italianDate(out);
}
